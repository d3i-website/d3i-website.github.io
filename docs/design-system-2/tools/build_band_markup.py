#!/usr/bin/env python3
"""Copy the front page's band drawing from _includes/home/band.html into components/bundle.js.

The band's drawing (about 31 KB of SVG and markup, computed by
docs/front-page-reference/source/build.py) is not redrawn in React. This script takes the
include, swaps its Liquid title lines and subtitle for placeholders, and writes the result
between the `/* @band-markup:start */` and `/* @band-markup:end */` lines of bundle.js as two
JS string constants:

    BAND_CLIPS   the inside of the hidden <svg> before the band: the clip paths of the two
                 portraits (#i, #j)
    BAND_MARKUP  the inside of <div class="hero__band">, with @@TITLE_LINE_1@@,
                 @@TITLE_LINE_2@@ and @@SUBTITLE@@ where the include outputs page.title_line_1,
                 page.title_line_2 and page.excerpt

D3I.Band renders the wrappers itself, fills the placeholders with its escaped props, and puts
its children where the include outputs include.note. The include's shape is checked exactly;
if band.html changes shape, this script stops and says where, and Band needs a look too.

    python3 -I docs/design-system-2/tools/build_band_markup.py          rewrite the region
    python3 -I docs/design-system-2/tools/build_band_markup.py --check  exit 1 if it is out of date
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent.parent
INCLUDE = ROOT / "_includes/home/band.html"
BUNDLE = ROOT / "docs/design-system-2/project/components/bundle.js"

START = "/* @band-markup:start */"
END = "/* @band-markup:end */"

# The include's outer shape, which Band renders as React elements (keep the two in step).
SHAPE = re.compile(
    r"\A\{% comment %\}.*?\{% endcomment %\}\n"
    r'<svg width="0" height="0" style="position:absolute" aria-hidden="true">(?P<clips>.*?)</svg>\s*'
    r'<section class="hero">\s*'
    r'<div class="hero__band">(?P<band>.*)</div>\s*'
    r"\{\{ include\.note \}\}\s*"
    r"</section>\s*\Z",
    re.S,
)
PLACEHOLDERS = {
    "{{ page.title_line_1 }}": "@@TITLE_LINE_1@@",
    "{{ page.title_line_2 }}": "@@TITLE_LINE_2@@",
    "{{ page.excerpt }}": "@@SUBTITLE@@",
}


def fail(msg):
    sys.exit(f"build_band_markup: {msg}")


def region():
    """The generated lines, indented as bundle.js's body is."""
    m = SHAPE.match(INCLUDE.read_text())
    if not m:
        fail(f"{INCLUDE.relative_to(ROOT)} no longer has the shape Band renders: a comment, the hidden "
             "clip-path <svg>, then <section class=\"hero\"> holding <div class=\"hero__band\"> and "
             "{{ include.note }}")
    band = m.group("band").strip()
    for liquid, placeholder in PLACEHOLDERS.items():
        if band.count(liquid) != 1:
            fail(f"expected {liquid} once in the band, found it {band.count(liquid)} times")
        band = band.replace(liquid, placeholder)
    clips = m.group("clips")
    for name, text in (("the clip paths", clips), ("the band", band)):
        if "{{" in text or "{%" in text:
            fail(f"Liquid left in {name} that Band does not fill")
    return "\n".join([
        "  /* Generated by tools/build_band_markup.py from _includes/home/band.html; do not edit. */",
        f"  var BAND_CLIPS = {json.dumps(clips)};",
        f"  var BAND_MARKUP = {json.dumps(band)};",
    ])


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    src = BUNDLE.read_text()
    m = re.search(r"^([ \t]*)" + re.escape(START) + r"\n(.*?)^[ \t]*" + re.escape(END) + "$", src, re.S | re.M)
    if not m:
        fail(f"no {START} … {END} region in {BUNDLE.relative_to(ROOT)}")
    new = region() + "\n"
    if m.group(2) == new:
        return
    if check:
        fail("the band markup in bundle.js is out of date: run tools/build_band_markup.py")
    BUNDLE.write_text(src[: m.start(2)] + new + src[m.end(2):])
    print(f"wrote the band markup into {BUNDLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
