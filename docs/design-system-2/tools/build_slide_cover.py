#!/usr/bin/env python3
"""Copy the network cover's band from project/assets/Slides/cover-network.svg into components/bundle.js.

The drawing is cover B9 of the slides checkpoint: the front page band's own drawing, laid out
1680px wide and enlarged 8/7 to the slide, spread across it with one downturn and the D3I mark
on the story's upper line. It was read once from the mockup's rendered page into one standalone
SVG in slide pixels; that file is the source. This script writes it between the
`/* @slide-cover:start */` and `/* @slide-cover:end */` lines of bundle.js as one JS string:

    SLIDE_COVER_NETWORK  the <svg> without its comment and xmlns, with @@MARK_SRC@@ where the file
                         points at ../Logos/d3i-mark.svg

D3I.SlideCover fills @@MARK_SRC@@ with its markSrc prop (escaped), or drops the <image> when there
is none. Every colour in the file must be the light value of a colour token in tokens.json, or one of
the band artwork's own (a colour in an assets/Network/*.svg file: the portraits keep the designer's
colours, as pictures are never recoloured); the script stops and names any other. design-system.json records
the file under the Slides asset group (uploaded at install); the script also stops if the size it
records is not the file's.

    python3 -I docs/design-system-2/tools/build_slide_cover.py          rewrite the region
    python3 -I docs/design-system-2/tools/build_slide_cover.py --check  exit 1 if it is out of date
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent.parent
PROJECT = ROOT / "docs/design-system-2/project"
SOURCE = PROJECT / "assets/Slides/cover-network.svg"
TOKENS = PROJECT / "tokens.json"
NETWORK = PROJECT / "assets/Network"
BUNDLE = PROJECT / "components/bundle.js"
INDEX = PROJECT / "design-system.json"

START = "/* @slide-cover:start */"
END = "/* @slide-cover:end */"
MARK = 'href="../Logos/d3i-mark.svg"'


def fail(msg):
    sys.exit(f"build_slide_cover: {msg}")


def token_colours():
    tokens = json.loads(TOKENS.read_text())["color"]["tokens"]
    by_name = {t["name"]: t["value"] for t in tokens}

    def light(v):
        s = v if isinstance(v, str) else v["light"]
        ref = re.fullmatch(r"\{(.+)\}", s)
        return light(by_name[ref[1]]) if ref else s.lower()

    return {light(t["value"]) for t in tokens}


def artwork_colours():
    return {c.lower() for f in NETWORK.glob("*.svg") for c in re.findall(r"#[0-9a-fA-F]{3,8}\b", f.read_text())}


def region():
    svg = SOURCE.read_text()
    svg = re.sub(r"<!--.*?-->\s*", "", svg, flags=re.S).strip()
    if not svg.startswith("<svg ") or not svg.endswith("</svg>"):
        fail(f"{SOURCE.relative_to(ROOT)} is not one <svg> element")
    svg = svg.replace(' xmlns="http://www.w3.org/2000/svg"', "", 1)
    if svg.count(MARK) != 1 or svg.count("<image ") != 1:
        fail(f"expected one <image {MARK}> (the D3I mark) in the drawing")
    svg = svg.replace(MARK, 'href="@@MARK_SRC@@"')
    allowed = token_colours() | artwork_colours()
    odd = sorted({c.lower() for c in re.findall(r"#[0-9a-fA-F]{3,8}\b", svg)} - allowed)
    if odd or re.search(r"rgba?\(", svg):
        fail(f"colours that are neither a token's light value nor the band artwork's own: {', '.join(odd) or 'rgb()'}")
    svg = re.sub(r">\s+<", "><", svg)
    return "\n".join([
        "  /* Generated by tools/build_slide_cover.py from project/assets/Slides/cover-network.svg; do not edit. */",
        f"  var SLIDE_COVER_NETWORK = {json.dumps(svg)};",
    ])


def check_index():
    rec = json.loads(INDEX.read_text())["assetGroups"].get("Slides", {}).get("files", {}).get(SOURCE.name)
    if not rec:
        fail(f"{INDEX.relative_to(ROOT)} records no Slides/{SOURCE.name}")
    if rec["size"] != SOURCE.stat().st_size:
        fail(f"{INDEX.relative_to(ROOT)} records Slides/{SOURCE.name} at {rec['size']} bytes; the file has {SOURCE.stat().st_size}")


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    check_index()
    src = BUNDLE.read_text()
    m = re.search(r"^([ \t]*)" + re.escape(START) + r"\n(.*?)^[ \t]*" + re.escape(END) + "$", src, re.S | re.M)
    if not m:
        fail(f"no {START} … {END} region in {BUNDLE.relative_to(ROOT)}")
    new = region() + "\n"
    if m.group(2) == new:
        return
    if check:
        fail("the network cover in bundle.js is out of date: run tools/build_slide_cover.py")
    BUNDLE.write_text(src[: m.start(2)] + new + src[m.end(2):])
    print(f"wrote the network cover into {BUNDLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
