#!/usr/bin/env python3
"""Install this design system into a claude.ai Design System artifact you own, or re-sync one.

A Design System artifact keeps its own copy of everything, and every image it shows is an
upload with an id that only exists in that artifact. This script does the mechanical part
of a copy; Claude does the Artifact calls in between. INSTALL.md walks through the order.

  batches   Print the image uploads as JSON arrays of absolute paths, 25 per array (the
            most one upload call takes). With --existing-index, only the images that are
            new or changed since that copy was made.
  stage     Read the upload results, then write a publishable tree to --out: every file
            under project/ except the images, the preview image URLs pointed at the new
            uploads, a new index, and publish.json with the arguments for the publish call.
  adopt     After publishing and copying the artifact's index to project/design-system.json, give
            the repository's text files the ids that were published: every /_blob/<old id> under
            project/ becomes the new id of the same image. The old index (path -> old id) is
            the repository's index as last committed (git HEAD), or --old-index; the current
            index (path -> new id) is joined to it, so no staged tree is needed.

A file recorded without a "blob" (the Slides and Network groups) is new to every copy, so
batches always lists it too, and stage fails, naming each file, if any image is left without
an upload id after reading the results.

A file recorded with "placeholder": true has an id that was never uploaded (the MD5 of its
bytes), so that a preview can point at it. batches always lists it, and stage replaces its
id like any other and drops the flag from the staged index.

  python3 -I docs/design-system-2/tools/install_copy.py batches
  python3 -I docs/design-system-2/tools/install_copy.py stage --uploads RESULTS.txt --out DIR --by "Name"
"""
import argparse
import datetime
import json
import pathlib
import re
import shutil
import subprocess
import sys

DS = pathlib.Path(__file__).resolve().parent.parent
PROJECT = DS / "project"
IMAGE_TYPES = {".svg", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".mp4", ".webm", ".pdf"}
# Generated by the artifact page; a copy never publishes them.
TEXT_TYPES = {".html", ".md", ".js", ".ts", ".css", ".json"}
SKIP = {"tokens.css", "manifest.json"}
# One line of an upload result:
# - "/abs/…/project/assets/Logos/eyra.png" (16091 bytes, image/png) → "/_blob/<id>" (id <id>)
RESULT = re.compile(r'"(?P<path>[^"]+)" \((?P<size>\d+) bytes, (?P<type>[^)]*)\) → "/_blob/(?P<id1>[0-9a-f]{32})" \(id (?P<id2>[0-9a-f]{32})\)')
BLOB = re.compile(r"/_blob/([0-9a-f]{32})")


def die(msg):
    sys.exit("install_copy: " + msg)


INDEX = PROJECT / "design-system.json"  # --index overrides it (the tests use a fixture)


def repo_index():
    return json.loads(INDEX.read_text())


def images(index):
    """Every image the index records, in tile order: (key "Group/name", record)."""
    for group in index["groups"]:
        grp = index["assetGroups"][group]
        for name in grp.get("order") or list(grp["files"]):
            yield f"{group}/{name}", grp["files"][name]


def placeholders(index):
    """Images recorded with a placeholder id ("placeholder": true): never uploaded yet, though a
    preview points at the id. A copy always uploads them, whatever an existing copy records."""
    return {key for key, rec in images(index) if rec.get("placeholder")}


def reusable(existing_path):
    """Images whose name and size are unchanged in an existing copy keep that copy's upload,
    except those this repository records with a placeholder id. "Unchanged" compares the file's
    size with the record's source_size (an SVG the store normalized) or else its size."""
    if not existing_path:
        return {}
    existing = json.loads(pathlib.Path(existing_path).read_text())
    fresh = placeholders(repo_index())
    keep = {}
    for key, rec in images(existing):
        local = PROJECT / "assets" / key
        if key not in fresh and not rec.get("placeholder") and "blob" in rec and local.is_file() and local.stat().st_size == rec.get("source_size", rec["size"]):
            keep[key] = rec
    return keep


def cmd_batches(args):
    keep = reusable(args.existing_index)
    todo = [str(PROJECT / "assets" / key) for key, _ in images(repo_index()) if key not in keep]
    for i in range(0, len(todo), 25):
        print(json.dumps(todo[i:i + 25]))
    print(f"# {len(todo)} to upload, {len(keep)} reused", file=sys.stderr)


def parse_uploads(text):
    """Map "Group/name" -> (new upload id, stored size) from pasted upload results, checking each line.
    The store normalizes SVGs on upload, so only an SVG may come back at a different size."""
    found = {}
    for m in RESULT.finditer(text):
        if m["id1"] != m["id2"]:
            die(f"the two ids on the line for {m['path']} differ: the results were not copied exactly")
        parts = pathlib.PurePosixPath(m["path"]).parts
        if "assets" not in parts:
            die(f"{m['path']} is not under project/assets/")
        key = "/".join(parts[len(parts) - 1 - parts[::-1].index("assets") + 1:])
        local = PROJECT / "assets" / key
        if not local.is_file():
            die(f"{key} was uploaded but is not in project/assets/")
        if local.stat().st_size != int(m["size"]) and m["type"] != "image/svg+xml":
            die(f"{key}: uploaded {m['size']} bytes, the repository file has {local.stat().st_size}")
        found[key] = (m["id1"], int(m["size"]))
    return found


def git_ref():
    try:
        sha = subprocess.run(["git", "-C", str(DS), "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(DS), "status", "--porcelain", "--", "."], capture_output=True, text=True, check=True).stdout.strip()
        return sha + ("+local changes" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def cmd_stage(args):
    src = repo_index()
    new_ids = parse_uploads(pathlib.Path(args.uploads).read_text()) if args.uploads else {}
    keep = reusable(args.existing_index)
    ids = {**{k: (rec["blob"], rec["size"], rec.get("source_size")) for k, rec in keep.items()},
           **{k: (i, size, None) for k, (i, size) in new_ids.items()}}
    missing = [key for key, _ in images(src) if key not in ids]
    if missing:
        die(f"{len(missing)} images have no upload id: {', '.join(missing)}; upload them and add their results")

    out = pathlib.Path(args.out).resolve()
    if (out / "project").exists():
        shutil.rmtree(out / "project")
    # a file recorded before its first upload (no "blob" yet) has no old id for the text to point at;
    # a placeholder id is an old id like any other, and is replaced by the upload's
    old_to_new = {rec["blob"]: ids[key][0] for key, rec in images(src) if "blob" in rec}

    staged = []
    for path in sorted(PROJECT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(PROJECT).as_posix()
        if rel in SKIP or rel == "design-system.json" or rel.startswith("api/"):
            continue
        if rel.startswith("assets/") and path.suffix.lower() in IMAGE_TYPES:
            continue
        dest = out / "project" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if path.suffix in TEXT_TYPES:
            text = path.read_text()
            unknown = [b for b in BLOB.findall(text) if b not in old_to_new]
            if unknown:
                die(f"{rel} points at uploads the index does not record: {unknown[:3]}")
            dest.write_text(BLOB.sub(lambda m: "/_blob/" + old_to_new[m[1]], text))
        else:
            shutil.copyfile(path, dest)
        staged.append(rel)

    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if args.existing_index:
        index = json.loads(pathlib.Path(args.existing_index).read_text())
        note = f"Re-synced from docs/design-system-2: {len(new_ids)} images uploaded, {len(keep)} kept."
    else:
        index = {"v": 3, "layout": "files", "createdOnFiles": {"v": 1, "at": now}, "title": args.title,
                 "sections": {}, "blobs": {}, "docs": {"readme": "project/README.md", "sections": []}}
        note = "Installed from docs/design-system-2 in d3i-website/d3i-website.github.io."
    for key in ("namespace", "libraries", "groups"):
        index[key] = src[key]
    groups = {}
    for name in src["groups"]:
        grp = json.loads(json.dumps(src["assetGroups"][name]))
        for rec in grp["files"].values():
            blob, size, _ = ids[f"{name}/{rec['name']}"]
            repo_size = rec["size"]
            rec["blob"] = blob
            rec["size"] = size  # what the artifact holds
            if size != repo_size:
                rec["source_size"] = repo_size
            rec.pop("sha256", None)
            rec.pop("placeholder", None)
        groups[name] = grp
    index["assetGroups"] = groups
    index["lastChange"] = {"by": args.by, "at": now, "via": f"Claude Code · d3i-website/d3i-website.github.io@{git_ref()}", "note": note}
    (out / "project" / "design-system.json").write_text(json.dumps(index, ensure_ascii=False, separators=(",", ":")))

    files = {}
    for rel in staged:
        key = "project/" + rel
        files[key] = {"from": key, "contentType": "text/plain"} if rel.endswith(".d.ts") else key
    first = "project/README.md"
    files.pop(first)
    if len(files) + 1 > 255:
        die(f"{len(files) + 1} files is more than one publish call takes (255)")
    publish = {"root": str(out), "file_path": str(out / first), "files": files,
               "index_file_path": str(out / "project" / "design-system.json")}
    (out / "publish.json").write_text(json.dumps(publish, indent=1))
    print(f"staged {len(staged)} files and the index in {out}; {len(new_ids)} new uploads, {len(keep)} reused")
    print(f"publish arguments: {out / 'publish.json'}")


def by_key(index):
    return {key: rec["blob"] for key, rec in images(index) if "blob" in rec}


def adoption_map(old_index, new_index):
    """old id -> new id, joining the two indexes on "Group/name". Refuses when one old id would
    become two new ids (two files that shared a placeholder id)."""
    new = by_key(new_index)
    mapping, source = {}, {}
    for key, old in by_key(old_index).items():
        if key not in new:
            continue
        if mapping.setdefault(old, new[key]) != new[key]:
            die(f"old id {old} maps to both {mapping[old]} ({source[old]}) and {new[key]} ({key}): cannot tell which a preview means")
        source.setdefault(old, key)
    return mapping


def adopt(project, old_index, new_index):
    """Rewrite the text files under project/ so every /_blob/<id> is an id in new_index.
    Returns (files changed, ids rewritten). Binary files and design-system.json are not touched."""
    mapping = adoption_map(old_index, new_index)
    known = set(by_key(new_index).values())
    changed = rewritten = 0
    for path in sorted(project.rglob("*")):
        if not path.is_file() or path.suffix not in TEXT_TYPES or path.name == "design-system.json" and path.parent == project:
            continue
        text = path.read_text()
        unknown = sorted({b for b in BLOB.findall(text) if b not in mapping and b not in known})
        if unknown:
            die(f"{path.relative_to(project).as_posix()} points at {unknown[:3]}, which neither index records. "
                "If you already committed the new index, pass the previous one with --old-index "
                "(e.g. `git show HEAD~1:docs/design-system-2/project/design-system.json > /tmp/old.json`).")
        count = sum(1 for b in BLOB.findall(text) if b in mapping and mapping[b] != b)
        if count:
            path.write_text(BLOB.sub(lambda m: "/_blob/" + mapping.get(m[1], m[1]), text))
            changed += 1
            rewritten += count
    return changed, rewritten


def cmd_adopt(args):
    if args.old_index:
        old = json.loads(pathlib.Path(args.old_index).read_text())
    else:
        top = subprocess.run(["git", "-C", str(DS), "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip()
        rel = INDEX.resolve().relative_to(top).as_posix()
        shown = subprocess.run(["git", "-C", str(DS), "show", "HEAD:" + rel], capture_output=True, text=True)
        if shown.returncode:
            die("could not read the committed index; pass --old-index")
        old = json.loads(shown.stdout)
    changed, rewritten = adopt(INDEX.parent, old, repo_index())
    print(f"adopted: {rewritten} ids rewritten in {changed} files")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("batches", help="print the image upload batches")
    b.add_argument("--index", help="the repository's index to read (default: project/design-system.json)")
    b.add_argument("--existing-index", help="the copy's project/design-system.json, read from it, for a re-sync")
    s = sub.add_parser("stage", help="stage the files and the index for publishing")
    s.add_argument("--uploads", help="a text file holding the upload results, copied exactly")
    s.add_argument("--out", required=True, help="the folder to stage in (the publish call's root)")
    s.add_argument("--title", default="datadonation.eu 2026", help="the new system's name (ignored on a re-sync, which keeps the copy's title)")
    s.add_argument("--by", default="Claude", help="the person the copy is installed for")
    s.add_argument("--index", help="the repository's index to read (default: project/design-system.json)")
    s.add_argument("--existing-index", help="the copy's project/design-system.json, read from it, for a re-sync")
    a = sub.add_parser("adopt", help="point the repository's text files at the published upload ids")
    a.add_argument("--index", help="the repository's (new) index (default: project/design-system.json)")
    a.add_argument("--old-index", help="the index the files' ids come from (default: the committed one, git HEAD)")
    args = p.parse_args()
    if args.index:
        global INDEX
        INDEX = pathlib.Path(args.index)
    {"batches": cmd_batches, "stage": cmd_stage, "adopt": cmd_adopt}[args.cmd](args)


if __name__ == "__main__":
    main()
