#!/usr/bin/env python3
"""Install this design system into a claude.ai Design System artifact you own, or re-sync one.

A Design System artifact keeps its own copy of everything, and every image it shows is an
upload with an id that only exists in that artifact. This script does the mechanical part
of a copy; Claude does the Artifact calls in between. INSTALL.md walks through the order.

  batches   Print the image uploads as JSON arrays of absolute paths, 25 per array (the
            most one upload call takes). With --existing-index, only the images that are
            new or changed since that copy was made.
  stage     Read the upload results, then write a publishable tree to --out: every file
            under project/ except the images, the preview image URLs pointed at the new
            uploads, a new index, and publish.json with the arguments for the publish call.

  python3 -I docs/design-system/tools/install_copy.py batches
  python3 -I docs/design-system/tools/install_copy.py stage --uploads RESULTS.txt --out DIR --by "Name"
"""
import argparse
import datetime
import json
import pathlib
import re
import shutil
import subprocess
import sys

DS = pathlib.Path(__file__).resolve().parent.parent
PROJECT = DS / "project"
IMAGE_TYPES = {".svg", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".mp4", ".webm", ".pdf"}
# Generated by the artifact page; a copy never publishes them.
SKIP = {"tokens.css", "manifest.json"}
# One line of an upload result:
# - "/abs/…/project/assets/Logos/eyra.png" (16091 bytes, image/png) → "/_blob/<id>" (id <id>)
RESULT = re.compile(r'"(?P<path>[^"]+)" \((?P<size>\d+) bytes, [^)]*\) → "/_blob/(?P<id1>[0-9a-f]{32})" \(id (?P<id2>[0-9a-f]{32})\)')
BLOB = re.compile(r"/_blob/([0-9a-f]{32})")


def die(msg):
    sys.exit("install_copy: " + msg)


def repo_index():
    return json.loads((PROJECT / "design-system.json").read_text())


def images(index):
    """Every image the index records, in tile order: (key "Group/name", record)."""
    for group in index["groups"]:
        grp = index["assetGroups"][group]
        for name in grp.get("order") or list(grp["files"]):
            yield f"{group}/{name}", grp["files"][name]


def reusable(existing_path):
    """Images whose name and size are unchanged in an existing copy keep that copy's upload."""
    if not existing_path:
        return {}
    existing = json.loads(pathlib.Path(existing_path).read_text())
    keep = {}
    for key, rec in images(existing):
        local = PROJECT / "assets" / key
        if local.is_file() and local.stat().st_size == rec["size"]:
            keep[key] = rec["blob"]
    return keep


def cmd_batches(args):
    keep = reusable(args.existing_index)
    todo = [str(PROJECT / "assets" / key) for key, _ in images(repo_index()) if key not in keep]
    for i in range(0, len(todo), 25):
        print(json.dumps(todo[i:i + 25]))
    print(f"# {len(todo)} to upload, {len(keep)} reused", file=sys.stderr)


def parse_uploads(text):
    """Map "Group/name" -> new upload id from pasted upload results, checking each line."""
    found = {}
    for m in RESULT.finditer(text):
        if m["id1"] != m["id2"]:
            die(f"the two ids on the line for {m['path']} differ: the results were not copied exactly")
        parts = pathlib.PurePosixPath(m["path"]).parts
        if "assets" not in parts:
            die(f"{m['path']} is not under project/assets/")
        key = "/".join(parts[len(parts) - 1 - parts[::-1].index("assets") + 1:])
        local = PROJECT / "assets" / key
        if not local.is_file():
            die(f"{key} was uploaded but is not in project/assets/")
        if local.stat().st_size != int(m["size"]):
            die(f"{key}: uploaded {m['size']} bytes, the repository file has {local.stat().st_size}")
        found[key] = m["id1"]
    return found


def git_ref():
    try:
        sha = subprocess.run(["git", "-C", str(DS), "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(DS), "status", "--porcelain", "--", "."], capture_output=True, text=True, check=True).stdout.strip()
        return sha + ("+local changes" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def cmd_stage(args):
    src = repo_index()
    new_ids = parse_uploads(pathlib.Path(args.uploads).read_text()) if args.uploads else {}
    keep = reusable(args.existing_index)
    ids = {**keep, **new_ids}
    missing = [key for key, _ in images(src) if key not in ids]
    if missing:
        die(f"{len(missing)} images have no upload yet, e.g. {missing[:3]}; upload them and add their results")

    out = pathlib.Path(args.out).resolve()
    if (out / "project").exists():
        shutil.rmtree(out / "project")
    old_to_new = {rec["blob"]: ids[key] for key, rec in images(src)}

    staged = []
    for path in sorted(PROJECT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(PROJECT).as_posix()
        if rel in SKIP or rel == "design-system.json" or rel.startswith("api/"):
            continue
        if rel.startswith("assets/") and path.suffix.lower() in IMAGE_TYPES:
            continue
        dest = out / "project" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if path.suffix in {".html", ".md", ".js", ".ts", ".css", ".json"}:
            text = path.read_text()
            unknown = [b for b in BLOB.findall(text) if b not in old_to_new]
            if unknown:
                die(f"{rel} points at uploads the index does not record: {unknown[:3]}")
            dest.write_text(BLOB.sub(lambda m: "/_blob/" + old_to_new[m[1]], text))
        else:
            shutil.copyfile(path, dest)
        staged.append(rel)

    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if args.existing_index:
        index = json.loads(pathlib.Path(args.existing_index).read_text())
        note = f"Re-synced from docs/design-system: {len(new_ids)} images uploaded, {len(keep)} kept."
    else:
        index = {"v": 3, "layout": "files", "createdOnFiles": {"v": 1, "at": now}, "title": args.title,
                 "sections": {}, "blobs": {}, "docs": {"readme": "project/README.md", "sections": []}}
        note = "Installed from docs/design-system in d3i-website/d3i-website.github.io."
    for key in ("namespace", "libraries", "groups"):
        index[key] = src[key]
    groups = {}
    for name in src["groups"]:
        grp = json.loads(json.dumps(src["assetGroups"][name]))
        for rec in grp["files"].values():
            rec["blob"] = ids[f"{name}/{rec['name']}"]
            rec.pop("sha256", None)
        groups[name] = grp
    index["assetGroups"] = groups
    index["lastChange"] = {"by": args.by, "at": now, "via": f"Claude Code · d3i-website/d3i-website.github.io@{git_ref()}", "note": note}
    (out / "project" / "design-system.json").write_text(json.dumps(index, ensure_ascii=False, separators=(",", ":")))

    files = {}
    for rel in staged:
        key = "project/" + rel
        files[key] = {"from": key, "contentType": "text/plain"} if rel.endswith(".d.ts") else key
    first = "project/README.md"
    files.pop(first)
    if len(files) + 1 > 255:
        die(f"{len(files) + 1} files is more than one publish call takes (255)")
    publish = {"root": str(out), "file_path": str(out / first), "files": files,
               "index_file_path": str(out / "project" / "design-system.json")}
    (out / "publish.json").write_text(json.dumps(publish, indent=1))
    print(f"staged {len(staged)} files and the index in {out}; {len(new_ids)} new uploads, {len(keep)} reused")
    print(f"publish arguments: {out / 'publish.json'}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("batches", help="print the image upload batches")
    b.add_argument("--existing-index", help="the copy's project/design-system.json, read from it, for a re-sync")
    s = sub.add_parser("stage", help="stage the files and the index for publishing")
    s.add_argument("--uploads", help="a text file holding the upload results, copied exactly")
    s.add_argument("--out", required=True, help="the folder to stage in (the publish call's root)")
    s.add_argument("--title", default="datadonation.eu", help="the new system's name (ignored on a re-sync)")
    s.add_argument("--by", default="Claude", help="the person the copy is installed for")
    s.add_argument("--existing-index", help="the copy's project/design-system.json, read from it, for a re-sync")
    args = p.parse_args()
    {"batches": cmd_batches, "stage": cmd_stage}[args.cmd](args)


if __name__ == "__main__":
    main()
